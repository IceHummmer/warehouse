let currentLanguage='en';
try{currentLanguage=localStorage.getItem('hh-wh-language')==='ru'?'ru':'en';}catch{}
export function getLanguage(){return currentLanguage;}
export function setLanguage(language){
  currentLanguage=language==='ru'?'ru':'en';
  try{localStorage.setItem('hh-wh-language',currentLanguage);}catch{}
  return currentLanguage;
}
export function t(english){
  const key=String(english??'');
  return currentLanguage==='ru'?(ru[key]??key):key;
}
export function localizeError(message){
  const original=String(message??'');
  if(currentLanguage!=='ru')return original;
  if(Object.hasOwn(ru,original))return ru[original];
  const match=original.match(/^(.*) \(HTTP (\d{3})\)\.$/);
  if(match&&Object.hasOwn(ru,match[1]))return ru[match[1]]+' (HTTP '+match[2]+').';
  return original;
}
